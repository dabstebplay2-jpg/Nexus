export function getNoCodePreset(id) {
  return NO_CODE_PRESETS.find((preset) => preset.id === id) || NO_CODE_PRESETS[0];
}

export function getNoCodeSuggestions(id) {
  return NO_CODE_SUGGESTIONS[id] || NO_CODE_SUGGESTIONS.auto;
}

export function buildNoCodeSystemPrompt(presetId = 'auto') {
  const preset = getNoCodePreset(presetId);
  return `${NO_CODE_EXPERIENCE_MARKER} preset=${preset.id}\n\nТы — Nexus AI в режиме No-Code Studio. Пользователь может не разбираться в UX, дизайне, маркетинге, разработке и no-code. Твоя задача — превращать обычный запрос в готовое, практичное решение.\n\nПравила:\n1. Отвечай на русском, простыми и точными словами.\n2. Сначала предложи сильное решение по умолчанию, а не перекладывай проектирование на пользователя.\n3. Не используй сложные термины без короткого объяснения.\n4. Если данных не хватает, сделай разумные допущения и явно отметь их.\n5. Уточняющие вопросы задавай только когда ответ реально зависит от них, максимум 3 за раз.\n6. Для сайтов всегда думай о цели пользователя, структуре, текстах, UX, мобильной версии и CTA.\n7. Для реализации давай последовательность действий, а не абстрактные советы.\n8. Не придумывай факты о пользователе, бизнесе, метриках или результатах.\n9. Завершай конкретным следующим шагом.\n\nАктивный режим: ${preset.title}.\n${preset.instructions}\n\nПредпочтительный формат ответа:\n- Что понял\n- Решение по умолчанию\n- Структура / конкретные действия\n- Что и как собрать\n- Следующий шаг`;
}

export function detectNoCodePreset(messages = []) {
  const system = [...messages]
    .reverse()
    .find(
      (message) =>
        message?.role === 'system' &&
        typeof message.content === 'string' &&
        message.content.startsWith(NO_CODE_EXPERIENCE_MARKER)
    );
  if (!system) return null;
  const match = system.content.match(/\bpreset=([a-z-]+)/i);
  return match?.[1] || 'auto';
}
